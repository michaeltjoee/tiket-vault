#!/usr/bin/env python3
"""Generate the vault's index files from page frontmatter and `> ` summary lines.

Writes:
  index.md                                  root map: one line per repo + shared index
  wiki/repos/<REPO>/<slug>-index.md         a repo's pages, its shared pages, other repos
  wiki/shared-index.md                      every concept, entity, decision and how-to
  wiki/repos/TIX-PASSPORT/passport-packages.md   the catalog table rows (rest of page kept)

Usage: build-index.py [--check]
  --check  write nothing; exit 1 if any output would change.

Standard library only (macOS system python3 is 3.9).
"""
import os
import re
import sys

VAULT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI = os.path.join(VAULT, "wiki")
SHARED_DIRS = [("concepts", "Concepts"), ("entities", "Entities"),
               ("decisions", "Decisions"), ("howto", "How-to")]
# Repos whose unit pages are left out of the session index; the catalog page lists them.
COLLAPSE = {
    "TIX-PASSPORT": {
        "catalog": "passport-packages",
        "unit_dir": "packages",
        "rule": "Package `packages/<x>` has the page `[[passport-<x>]]`. To find a package by purpose, open [[passport-packages]].",
    },
}
TOP_KINDS = ["overview", "architecture", "workflows"]
GEN_NOTE = "> Generated by `scripts/build-index.py` from page frontmatter and `> ` lines. Do not edit. Edit the pages, then commit with `scripts/commit.sh`."
KIND_INDEX = "kind: index"
FIND_RULE = "Open any `[[name]]` with `find wiki -name '<name>.md'` from the vault root."

warnings = []


def parse_frontmatter(text):
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}
    fm, key = {}, None
    for line in text[4:end].split("\n"):
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            if val.startswith("[") and val.endswith("]"):
                fm[key] = [v.strip().strip("\"'") for v in val[1:-1].split(",") if v.strip()]
            elif val == "":
                fm[key] = None
            else:
                fm[key] = val.strip("\"'")
        elif key and re.match(r"^\s+- ", line):
            if not isinstance(fm.get(key), list):
                fm[key] = []
            fm[key].append(line.split("- ", 1)[1].strip())
    return fm


def load_page(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    fm = parse_frontmatter(text)
    m = re.search(r"^> (.+)$", text, re.M)
    name = os.path.basename(path)[:-3]
    rel = os.path.relpath(path, VAULT)
    if not m:
        warnings.append("no `> ` summary line: " + rel)
    repos = fm.get("repos") or ([fm["repo"]] if fm.get("repo") else [])
    return {
        "name": name, "rel": rel, "fm": fm, "repos": repos,
        "kind": fm.get("kind") or "", "status": fm.get("status") or "current",
        "summary": m.group(1).strip() if m else "",
    }


def walk(root):
    pages = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for fn in sorted(filenames):
            if not fn.endswith(".md"):
                continue
            p = load_page(os.path.join(dirpath, fn))
            if p["fm"].get("generated") == "true":
                continue
            pages.append(p)
    return pages


def line(p):
    s = "- [[%s]] — %s" % (p["name"], p["summary"] or "(no summary)")
    if p["status"] == "deprecated":
        s += " *(deprecated)*"
    elif p["status"] == "branch-only":
        s += " *(branch-only: `%s`)*" % (p["fm"].get("branch") or "?")
    return s


def first_sentence(s):
    m = re.match(r"(.+?[.:])(\s|$)", s)
    return m.group(1).rstrip(":") + ("." if m.group(1).endswith(":") else "") if m else s


def frontmatter(title, extra):
    out = ["---", "title: " + title]
    out += extra
    out += ["generated: true", "---", ""]
    return "\n".join(out)


def sort_key(p):
    k = p["kind"]
    return (TOP_KINDS.index(k) if k in TOP_KINDS else len(TOP_KINDS), p["name"])


def shared_sections(pages, heading_level):
    out = []
    for folder, label in SHARED_DIRS:
        group = [p for p in pages if p["rel"].startswith("wiki/%s/" % folder)]
        if group:
            out += ["", "#" * heading_level + " " + label]
            out += [line(p) for p in sorted(group, key=lambda p: p["name"])]
    return out


def load_repos():
    repos = {}
    for r in sorted(os.listdir(os.path.join(WIKI, "repos"))):
        if not os.path.isdir(os.path.join(WIKI, "repos", r)):
            continue
        pages = walk(os.path.join(WIKI, "repos", r))
        overview = next((p for p in pages if p["kind"] == "overview" and p["name"].endswith("-overview")), None)
        if not overview:
            warnings.append("no <slug>-overview page in wiki/repos/" + r)
            continue
        repos[r] = {"slug": overview["name"][: -len("-overview")], "pages": pages, "overview": overview}
    return repos


def load_shared(repos):
    shared = []
    for folder, _ in SHARED_DIRS:
        shared += walk(os.path.join(WIKI, folder))
    for p in shared:
        warnings.extend("%s: unknown repo %s" % (p["rel"], r) for r in p["repos"] if r not in repos)
    return shared


def build_root(repos, shared):
    out = [frontmatter("Index", [KIND_INDEX, "tags: [kind/index]"]),
           "# Index", "", GEN_NOTE, "",
           "Each repo has its own index. A SessionStart hook loads the index of the repo you open. "
           "Read another repo's index or the shared index only when a task crosses repos. " + FIND_RULE,
           "", "## Repos"]
    for r, info in repos.items():
        out.append("- [[%s-index|%s]] — %s (%d pages)" % (info["slug"], r, info["overview"]["summary"], len(info["pages"])))
    out += ["", "## Shared",
            "- [[shared-index]] — %d concepts, entities, decisions and how-tos that span repos." % len(shared),
            "", "## Vault",
            "- [[CLAUDE]] — the schema: layers, naming, frontmatter, templates, operations.",
            "- [[log]] — append-only log of ingests, updates, syncs and lints.", ""]
    return "\n".join(out)


def build_shared(shared):
    out = [frontmatter("Shared index", [KIND_INDEX, "tags: [kind/index]"]),
           "# Shared index", "", GEN_NOTE, "",
           "Every page that spans repos. Each repo index repeats the ones tagged for that repo."]
    out += shared_sections(shared, 2)
    return "\n".join(out) + "\n"


def build_repo_index(r, repos, shared):
    info = repos[r]
    coll = COLLAPSE.get(r)
    listed, hidden = info["pages"], []
    if coll:
        prefix = "wiki/repos/%s/%s/" % (r, coll["unit_dir"])
        hidden = [p for p in listed if p["rel"].startswith(prefix)]
        listed = [p for p in listed if not p["rel"].startswith(prefix)]
    out = [frontmatter("%s index" % r, ["repo: " + r, KIND_INDEX, "tags: [repo/%s, kind/index]" % info["slug"]]),
           "# %s index" % r, "", GEN_NOTE, "", "## Pages"]
    out += [line(p) for p in sorted(listed, key=sort_key)]
    if coll:
        out += ["", "%d package pages are not listed here. %s" % (len(hidden), coll["rule"])]
    mine = [p for p in shared if r in p["repos"]]
    out += ["", "## Shared", "Pages that span repos and cover %s. The full list is in [[shared-index]]." % r]
    out += shared_sections(mine, 3) if mine else ["", "(none tagged yet)"]
    out += ["", "## Elsewhere", FIND_RULE + " Read another repo's index only to discover pages there."]
    out += ["- [[%s-index|%s]] — %s" % (i2["slug"], r2, first_sentence(i2["overview"]["summary"]))
            for r2, i2 in repos.items() if r2 != r]
    out.append("- [[index]] — the root index.")
    return "\n".join(out) + "\n"


def catalog_row(p):
    npm = p["fm"].get("npm") or ""
    if not npm:
        warnings.append("no npm: in " + p["rel"])
    if p["name"] == "passport-umbrella":
        u = "—"
    else:
        u = "U" if p["fm"].get("umbrella") == "true" else ""
    summary = p["summary"].replace("|", "\\|")
    if p["status"] == "deprecated":
        summary += " *(deprecated)*"
    return "| [[%s]] | `%s` | %s | %s |" % (p["name"], npm, u, summary)


def build_catalog(pages, rel):
    """Rewrite only the table rows of the Passport catalog; the rest of the page is hand-written."""
    with open(os.path.join(VAULT, rel), encoding="utf-8") as f:
        text = f.read()
    pkgs = sorted((p for p in pages if p["rel"].startswith("wiki/repos/TIX-PASSPORT/packages/")), key=lambda p: p["name"])
    rows = "\n".join(catalog_row(p) for p in pkgs) + "\n"
    new, n = re.subn(r"(\| Page \| npm \| U \| Purpose \|\n\|---\|---\|---\|---\|\n)(?:\|.*\n)*",
                     lambda m: m.group(1) + rows, text, count=1)
    if n != 1:
        warnings.append("catalog table header not found in " + rel)
        return None
    return new


def write_outputs(outputs, check):
    changed = []
    for rel, content in outputs.items():
        path = os.path.join(VAULT, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old == content:
            continue
        changed.append(rel)
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
    return changed


def main():
    check = "--check" in sys.argv[1:]
    repos = load_repos()
    shared = load_shared(repos)
    outputs = {"index.md": build_root(repos, shared), "wiki/shared-index.md": build_shared(shared)}
    for r, info in repos.items():
        outputs["wiki/repos/%s/%s-index.md" % (r, info["slug"])] = build_repo_index(r, repos, shared)
    if "TIX-PASSPORT" in repos:
        rel = "wiki/repos/TIX-PASSPORT/passport-packages.md"
        catalog = build_catalog(repos["TIX-PASSPORT"]["pages"], rel)
        if catalog is not None:
            outputs[rel] = catalog
    changed = write_outputs(outputs, check)

    for w in warnings:
        print("WARN " + w, file=sys.stderr)
    for rel in changed:
        print(("STALE " if check else "wrote ") + rel)
    if check and changed:
        print("index files are out of date: run scripts/build-index.py (or commit with scripts/commit.sh)", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
